import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(join(root, 'file-types.json'), 'utf8'));
assert.equal(catalog.version, 1);
const extensions = new Set(), names = new Set(), ids = new Set();
const validGroups = new Set(['image','video','audio','media','sourceCode','document','archive','executable']);
for (const type of catalog.types) {
    assert.ok(/^[a-z][a-z0-9-]*$/.test(type.id) && !ids.has(type.id), 'unique file type ID'); ids.add(type.id);
    assert.ok(type.name && typeof type.language === 'string');
    for (const ext of type.extensions) { assert.ok(/^[a-z0-9]+$/.test(ext) && !extensions.has(ext), `duplicate/invalid extension: ${ext}`); extensions.add(ext); }
    for (const name of type.filenames) { assert.ok(!names.has(name.toLowerCase()), `duplicate filename: ${name}`); names.add(name.toLowerCase()); }
    assert.ok(type.groups.every(group => validGroups.has(group)));
    for (const asset of [type.icon, type.png]) { assert.ok(/^icons\/files\/[a-z0-9-]+\.(svg|png)$/.test(asset)); readFileSync(join(root, asset)); }
}
assert.equal(catalog.types.at(-1).id, 'file', 'fallback must be last');
const q = value => 'L' + JSON.stringify(value);
const packed = values => '|' + values.join('|') + '|';
const header = `// Generated by Lintel conformance/sync-file-types.mjs. Do not edit.
#pragma once
#include <algorithm>
#include <cwctype>
#include <string>
#include <string_view>
namespace Lintel
{
    struct FileType { std::wstring_view id, name, extensions, filenames, language, groups, icon; };
    inline constexpr FileType FileTypes[] = {
${catalog.types.map(t => `        { ${[t.id,t.name,packed(t.extensions),packed(t.filenames.map(n=>n.toLowerCase())),t.language,packed(t.groups),`ms-appx:///IntegrationIcons/files/${t.id}.png`].map(q).join(', ')} },`).join('\n')}
    };
    inline std::wstring Lower(std::wstring_view value) { std::wstring out{ value }; std::transform(out.begin(),out.end(),out.begin(),[](wchar_t c){ return static_cast<wchar_t>(std::towlower(c)); }); return out; }
    inline std::wstring ExtensionOf(std::wstring_view target)
    {
        if (target.find(L"://") != target.npos) target = target.substr(0, target.find_first_of(L"?#"));
        const auto slash = target.find_last_of(L"/\\\\");
        const auto name = target.substr(slash == target.npos ? 0 : slash + 1);
        const auto dot = name.find_last_of(L'.');
        return dot == name.npos || dot == 0 ? std::wstring{} : Lower(name.substr(dot + 1));
    }
    inline bool Contains(std::wstring_view list, std::wstring_view value) { return !value.empty() && list.find(L"|" + std::wstring{value} + L"|") != list.npos; }
    inline const FileType& FindFileType(std::wstring_view path)
    {
        const auto extension = ExtensionOf(path);
        const auto name = Lower(path.substr(path.find_last_of(L"/\\\\") + 1));
        for (const auto& type : FileTypes) if (Contains(type.extensions, extension) || Contains(type.filenames, name)) return type;
        return FileTypes[std::size(FileTypes) - 1];
    }
    inline bool GroupContains(std::wstring_view group, std::wstring_view extension)
    {
        const auto lower = Lower(extension);
        for (const auto& type : FileTypes) if (Contains(type.extensions, lower) && Contains(type.groups, group)) return true;
        return false;
    }
}
`;
const ts = '// Generated by Lintel conformance/sync-file-types.mjs. Do not edit.\nexport const fileTypeCatalog = ' + JSON.stringify({...catalog,types:catalog.types.map(t=>({...t,icon:'data:image/svg+xml;base64,'+readFileSync(join(root,t.icon)).toString('base64')}))},null,4) + ' as const\n';
const args = process.argv.slice(2), check = args.includes('--check');
function output(flag, relative, content) {
    const i=args.indexOf(flag); if(i<0)return;
    assert.ok(args[i+1]); const dest=join(args[i+1],relative);
    if(check) assert.equal(readFileSync(dest,'utf8').replace(/\r\n/g,'\n'),content,`${dest}: stale catalog`);
    else { mkdirSync(dirname(dest),{recursive:true});writeFileSync(dest,content); }
}
output('--terminal','src/cascadia/inc/LintelFileTypes.g.h',header);
output('--torbie','tabby-links/src/fileTypes.generated.ts',ts);
const terminal=args.indexOf('--terminal');
if(terminal>=0) for(const type of catalog.types) {
    const source=join(root,type.png),dest=join(args[terminal+1],'src/cascadia/CascadiaPackage/IntegrationIcons/files',`${type.id}.png`);
    if(check) assert.deepEqual(readFileSync(dest),readFileSync(source),`${dest}: stale icon`);
    else {mkdirSync(dirname(dest),{recursive:true});copyFileSync(source,dest);}
}
console.log(`Validated ${catalog.types.length} file types, ${extensions.size} extensions, and shared icons.`);
